package com.animationapp.audio

import com.animationapp.model.AnimationProject
import kotlin.math.abs
import kotlin.math.sin

/**
 * Voiceover Amplitude Waveform Track & 1-Tap Auto-Lip-Sync Mouth Generator (Phase 22).
 *
 * Complements [LipSyncAudioEngine] by storing per-frame vocal amplitude (`0.0f..1.0f`),
 * rendering compact waveform bars (`▁▂▃▅▇`) on timeline frame pills, and auto-assigning
 * Preston Blair 2D Mouth Shapes (`A/I`, `O`, `E`, `U/W`, `M/B/P`) across the entire scene!
 */
object VoiceoverWaveformEngine {

    private val barChars = charArrayOf(' ', '▁', '▂', '▃', '▅', '▇')

    fun amplitudeToBarChar(amp: Float): String {
        if (amp <= 0.05f) return ""
        val idx = (amp.coerceIn(0f, 1f) * (barChars.size - 1)).toInt().coerceIn(1, barChars.lastIndex)
        return barChars[idx].toString()
    }

    /**
     * Generates a natural multi-syllable speech cadence waveform across all frames in [project]
     * and automatically assigns 2D Lip-Sync Mouth Chart phonemes to every frame!
     */
    fun autoGenerateDialogueWaveformAndMouths(project: AnimationProject) {
        val frames = project.frames
        for (i in 0 until frames.size) {
            val f = frames[i]
            // Natural speech syllable envelope (syllable peaks every ~4-5 frames with pauses)
            val syllableWave = abs(sin(i * 0.72)).toFloat()
            val phraseGate = if ((i % 14) in 11..13) 0.0f else 1.0f
            val amp = (syllableWave * phraseGate).coerceIn(0f, 1f)
            f.audioAmplitude = amp

            f.phonemeMarker = when {
                amp < 0.08f -> LipSyncPhoneme.NONE
                amp < 0.25f -> LipSyncPhoneme.M_B_P
                amp < 0.45f -> if (i % 2 == 0) LipSyncPhoneme.F_V else LipSyncPhoneme.L_TH
                amp < 0.68f -> if (i % 2 == 0) LipSyncPhoneme.E else LipSyncPhoneme.U
                amp < 0.85f -> LipSyncPhoneme.O
                else -> LipSyncPhoneme.A_I
            }
        }
    }

    /**
     * Generates a rhythmic musical beat track (e.g., every 4 frames) across all frames in [project].
     */
    fun generateRhythmBeatTrack(project: AnimationProject, beatIntervalFrames: Int = 4) {
        val interval = beatIntervalFrames.coerceAtLeast(2)
        val frames = project.frames
        for (i in 0 until frames.size) {
            val f = frames[i]
            val isDownbeat = (i % interval == 0)
            f.audioAmplitude = if (isDownbeat) 1.0f else 0.15f
            f.phonemeMarker = if (isDownbeat) LipSyncPhoneme.BEAT_CLICK else LipSyncPhoneme.NONE
        }
    }

    fun clearWaveformAndMarkers(project: AnimationProject) {
        for (f in project.frames) {
            f.audioAmplitude = 0f
            f.phonemeMarker = LipSyncPhoneme.NONE
        }
    }
}

